/** Язык по браузеру; русский — только если браузер сам его назвал. */
export function detectLocale() {
  const tag = (globalThis.navigator?.language ?? 'en').toLowerCase()
  if (tag.startsWith('ru')) return 'ru'
  if (tag.startsWith('zh')) return 'zh'
  return 'en'
}

/** Подставить `{name}` в строку словаря. */
function fill(template, params) {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (whole, key) => (key in params ? String(params[key]) : whole))
}

/**
 * Свой переводчик на случай, когда общей локали в сборке нет.
 * @param locale - язык словаря.
 * @returns функция перевода с тем же контрактом, что у локали DSH.
 */
export function fallbackTranslate(locale) {
  const dict = locale === 'zh' ? zh : locale === 'ru' ? ru : en
  return (key, params) => fill(dict[key] ?? en[key] ?? key, params)
}
